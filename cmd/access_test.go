const (
	fakeAccessToken    = "fake-access-token-for-tests"
	fakeGeneratedToken = "fake-generated-token-for-tests"
	fakeSessionToken   = "fake-session-token"
)

func TestResolveWebAccessToken(t *testing.T) {
	t.Parallel()
	generate := func() string { return fakeGeneratedToken }
	cases := []struct {
		name    string
		host    string
		env     string
		want    accessToken
		wantErr string
	}{
		{name: "loopback without env", host: "127.0.0.1", want: accessToken{}},
		{name: "localhost without env", host: "localhost", want: accessToken{}},
		{name: "loopback with env", host: "127.0.0.1", env: fakeAccessToken, want: accessToken{value: fakeAccessToken}},
		{name: "env is trimmed", host: "127.0.0.1", env: "  " + fakeAccessToken + "\n", want: accessToken{value: fakeAccessToken}},
		{name: "blank env counts as unset", host: "127.0.0.1", env: "   ", want: accessToken{}},
		{name: "remote with env", host: "0.0.0.0", env: fakeAccessToken, want: accessToken{value: fakeAccessToken}},
		{name: "remote without env generates", host: "0.0.0.0", want: accessToken{value: fakeGeneratedToken, generated: true}},
		{name: "empty host generates", host: "", want: accessToken{value: fakeGeneratedToken, generated: true}},
		{name: "env too short", host: "0.0.0.0", env: "short-token", wantErr: "at least 16 characters"},
		{name: "env too short on loopback", host: "127.0.0.1", env: "short-token", wantErr: "at least 16 characters"},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			getenv := func(key string) string {
				if key == accessTokenEnv {
					return tc.env
				}
				return ""
			}
			got, err := resolveWebAccessToken(tc.host, getenv, generate)
			if tc.wantErr != "" {
				require.ErrorContains(t, err, tc.wantErr)
				assert.NotContains(t, err.Error(), tc.env)
				return
			}
			require.NoError(t, err)
			assert.Equal(t, tc.want, got)
		})
	}
}

func TestResolveWebAccessTokenFailsWithoutEntropy(t *testing.T) {
	t.Parallel()
	_, err := resolveWebAccessToken("0.0.0.0", func(string) string { return "" }, func() string { return "" })
	require.ErrorContains(t, err, accessTokenEnv)
}

